"""Readable names for JadeEmpire.exe functions, for the recompiler's proc names.

python tools/funcnames.py unpacked/JadeEmpire.exe re > re/funcnames.txt

Writes `address name source`, one line per named function start. Sources, the
first that names a function wins:
  curated  re/names.txt
  ghidra   library functions Ghidra recognized in re/ghidra_funcs.txt
  method   the one `Class::Method` the function's own log or assert strings name
  nws      the NWScript engine function the action table dispatches to it
  file     the source file its assert strings name, or that the functions on
           both sides of it name (MSVC links each object file contiguously)
WHY: docs/exe_inventory.md §8
"""
import bisect, collections, re, struct, sys
import pefile

BASE = 0x400000
TEXT = (0x401000, 0x6e1000)
DATA = (0x6e1000, 0x895000)
METHOD = re.compile(rb"\b(C[A-Za-z0-9_]+)::(~?[A-Za-z_][A-Za-z0-9_]*)")
SRC = re.compile(rb"[ -~]{4,200}?\.cpp\x00", re.I)


def ident(s):
    """An identifier from a symbol: `FID_conflict:_free` -> `free`, `__87except` -> `fn_87except`."""
    s = s.split(":")[-1] if s.startswith("FID_conflict:") else s
    s = s.replace("~", "dtor_")
    s = re.sub(r"[^A-Za-z0-9]+", "_", s).strip("_")
    return "fn_" + s if s[:1].isdigit() else s


def string_refs(text, data, pattern):
    """{data VA of each match: (match, set of text offsets pushing/moving it)}."""
    out = {}
    for m in pattern.finditer(data):
        va = DATA[0] + m.start()
        pat = struct.pack("<I", va)
        refs, i = set(), text.find(pat)
        for _ in range(100000):
            if i < 0:
                break
            refs.add(TEXT[0] + i)
            i = text.find(pat, i + 1)
        if refs:
            out[va] = (m, refs)
    return out


def owner(fs, a):
    j = bisect.bisect_right(fs, a) - 1
    return fs[j] if j >= 0 else None


def methods(fs, text, data):
    """{function: Class_Method} for functions whose strings name one method."""
    seen = collections.defaultdict(set)
    for va, (_, refs) in string_refs(text, data, re.compile(rb"[ -~]{6,300}\x00")).items():
        s = data[va - DATA[0]:].split(b"\x00", 1)[0]
        for m in METHOD.finditer(s):
            for r in refs:
                seen[owner(fs, r)].add(m.group(1).decode() + "_" + ident(m.group(2).decode()))
    return {f: next(iter(n)) for f, n in seen.items() if f is not None and len(n) == 1}


def files(fs, text, data):
    """{function: file stem} from .cpp strings, filled across same-file gaps."""
    direct = collections.defaultdict(set)
    for va, (m, refs) in string_refs(text, data, SRC).items():
        name = re.split(rb"[\\/]", m.group()[:-1])[-1].decode().lower()
        if re.fullmatch(r"[\w.\-]+\.cpp", name):
            for r in refs:
                direct[owner(fs, r)].add(ident(name[:-4]))
    one = {f: next(iter(n)) for f, n in direct.items() if f is not None and len(n) == 1}
    marked = sorted(one)
    out = dict(one)
    for a, b in zip(marked, marked[1:]):
        if one[a] != one[b]:
            continue
        lo, hi = fs.index(a), fs.index(b)
        if any(f in direct for f in fs[lo + 1:hi]):
            continue
        for f in fs[lo + 1:hi]:
            out[f] = one[a]
    return out


def table(path, key=0, val=1):
    rows = []
    for l in open(path):
        if l.startswith("#") or not l.strip():
            continue
        p = l.rstrip("\n").split("\t") if "\t" in l else l.split()
        rows.append((p[key], p[val]))
    return rows


def nws(re_dir):
    """{handler: nws_Name}; a handler shared by several actions gets `_etc`."""
    names = dict(table(re_dir + "/nwscript_functions.tsv"))
    by = collections.defaultdict(list)
    for i, h in table(re_dir + "/nwscript_handlers.tsv"):
        if i.isdigit() and i in names:
            by[int(h, 16)].append(names[i])
    return {h: "nws_" + n[0] + ("_etc" if len(n) > 1 else "") for h, n in by.items()}


def main():
    exe, re_dir = sys.argv[1:3]
    img = pefile.PE(exe).get_memory_mapped_image()
    text = img[TEXT[0] - BASE:TEXT[1] - BASE]
    data = img[DATA[0] - BASE:DATA[1] - BASE]
    ghidra = [l.split() for l in open(re_dir + "/ghidra_funcs.txt") if l.strip()]
    fs = sorted(int(a, 16) for a, _ in ghidra)
    sources = [
        ("curated", {int(a, 16): n for a, n in table(re_dir + "/names.txt") if int(a, 16) < TEXT[1]}),
        ("ghidra", {int(a, 16): ident(n) for a, n in ghidra if not n.startswith("FUN_")}),
        ("method", methods(fs, text, data)),
        ("nws", nws(re_dir)),
        ("file", files(fs, text, data)),
    ]
    named = {}
    for src, m in sources:
        for a, n in m.items():
            if a not in named and TEXT[0] <= a < TEXT[1] and n:
                named[a] = (n, src)
    count = collections.Counter(s for _, s in named.values())
    print("# Generated by tools/funcnames.py. Do not edit; see docs/exe_inventory.md §8.")
    print("# " + ", ".join("%s %d" % (s, count[s]) for s, _ in sources) + " of %d functions" % len(fs))
    for a in sorted(named):
        print("%#x %s %s" % (a, named[a][0], named[a][1]))


if __name__ == "__main__":
    main()
