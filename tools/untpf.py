# Unpacks a Texmod .tpf: the file is a ZIP XORed with 0x3FA43FA4 (little-
# endian dword), entries under Texmod's fixed ZIP password. Writes every entry
# (texmod.def and the replacement images) flat into <out dir>.
# WHY: docs/rendering.md §4
# Usage: python3 -I tools/untpf.py <file.tpf> <out dir>
import sys, zipfile, io
d = bytearray(open(sys.argv[1], 'rb').read())
key = bytes([0xa4, 0x3f, 0xa4, 0x3f])
for i in range(len(d)): d[i] ^= key[i & 3]
pw = bytes([0x73,0x2A,0x63,0x7D,0x5F,0x0A,0xA6,0xBD,0x7D,0x65,0x7E,0x67,0x61,0x2A,0x7F,0x7F,0x74,0x61,0x67,0x5B,0x60,0x70,0x45,0x74,0x5C,0x22,0x74,0x5D,0x6E,0x6A,0x73,0x41,0x77,0x6E,0x46,0x47,0x77,0x49,0x0C,0x4B,0x46,0x6F])
z = zipfile.ZipFile(io.BytesIO(bytes(d)))
for n in z.namelist():
    print(n, z.getinfo(n).file_size)
    name = n.replace('\\', '/').split('/')[-1]
    assert name and '..' not in name
    open(f'{sys.argv[2]}/{name}', 'wb').write(z.read(n, pwd=pw))
